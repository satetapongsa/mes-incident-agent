-- 02_tables.sql : Remedy-style ticket tables, Opcenter-style MES tables, agent governance tables
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = MESAPP;
SET DEFINE OFF

------------------------------------------------------------------
-- Remedy side
------------------------------------------------------------------
CREATE SEQUENCE incident_seq START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE incidents (
  incident_id     VARCHAR2(15)   PRIMARY KEY,
  summary         VARCHAR2(200)  NOT NULL,
  description     VARCHAR2(4000),
  status          VARCHAR2(20)   DEFAULT 'New' NOT NULL
                  CONSTRAINT ck_inc_status CHECK (status IN ('New','Assigned','In Progress','Pending','Resolved','Closed')),
  priority        NUMBER(1)      DEFAULT 3 NOT NULL
                  CONSTRAINT ck_inc_priority CHECK (priority BETWEEN 1 AND 4),
  impact          VARCHAR2(30)   DEFAULT '3-Moderate/Limited',
  urgency         VARCHAR2(30)   DEFAULT '3-Medium',
  category_tier1  VARCHAR2(50),
  category_tier2  VARCHAR2(50),
  category_tier3  VARCHAR2(50),
  ci_name         VARCHAR2(50),
  assigned_group  VARCHAR2(60),
  assignee        VARCHAR2(60),
  submitter       VARCHAR2(60)   NOT NULL,
  source          VARCHAR2(20)   DEFAULT 'manual' NOT NULL
                  CONSTRAINT ck_inc_source CHECK (source IN ('manual','simulator','agent','script','import')),
  root_cause      VARCHAR2(2000),
  resolution      VARCHAR2(2000),
  external_ref    VARCHAR2(40),
  created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  resolved_at     TIMESTAMP,
  resolved_by     VARCHAR2(20)
                  CONSTRAINT ck_inc_resolved_by CHECK (resolved_by IN ('human','agent_approved'))
);
CREATE INDEX ix_inc_status   ON incidents(status);
CREATE INDEX ix_inc_cat3     ON incidents(category_tier3);
CREATE INDEX ix_inc_ci       ON incidents(ci_name);
CREATE INDEX ix_inc_created  ON incidents(created_at);
CREATE UNIQUE INDEX ux_inc_extref ON incidents(external_ref);

CREATE TABLE worklogs (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id  VARCHAR2(15) NOT NULL REFERENCES incidents(incident_id),
  author       VARCHAR2(60) NOT NULL,
  log_type     VARCHAR2(20) DEFAULT 'note' NOT NULL
               CONSTRAINT ck_wl_type CHECK (log_type IN ('note','agent_analysis','action','resolution')),
  text         CLOB NOT NULL,
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_wl_incident ON worklogs(incident_id);

------------------------------------------------------------------
-- MES side (Opcenter-like)
------------------------------------------------------------------
CREATE TABLE equipment (
  equipment_id      VARCHAR2(20) PRIMARY KEY,
  eq_type           VARCHAR2(40) NOT NULL,
  area              VARCHAR2(30) NOT NULL,
  operation         VARCHAR2(30) NOT NULL,
  state             VARCHAR2(20) DEFAULT 'Standby' NOT NULL
                    CONSTRAINT ck_eq_state CHECK (state IN ('Productive','Standby','Down','Engineering')),
  current_recipe    VARCHAR2(40),
  last_heartbeat    TIMESTAMP DEFAULT SYSTIMESTAMP,
  interface_status  VARCHAR2(20) DEFAULT 'Online' NOT NULL
                    CONSTRAINT ck_eq_if CHECK (interface_status IN ('Online','Offline','Timeout')),
  sim_fault         VARCHAR2(30),   -- set by the simulator only, never shown to the agent as "the answer"
  updated_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE SEQUENCE lot_seq START WITH 100 INCREMENT BY 1 NOCACHE;

CREATE TABLE lots (
  lot_id           VARCHAR2(20) PRIMARY KEY,
  product          VARCHAR2(30) NOT NULL,
  route            VARCHAR2(30) NOT NULL,
  operation        VARCHAR2(30) NOT NULL,
  equipment_id     VARCHAR2(20) REFERENCES equipment(equipment_id),
  status           VARCHAR2(20) DEFAULT 'Waiting' NOT NULL
                   CONSTRAINT ck_lot_status CHECK (status IN ('Waiting','Running','Hold','Completed')),
  hold_code        VARCHAR2(20),
  hold_reason      VARCHAR2(200),
  qty              NUMBER(6) NOT NULL,
  recipe_required  VARCHAR2(40) NOT NULL,
  updated_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE lot_history (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_id        VARCHAR2(20) NOT NULL REFERENCES lots(lot_id),
  event         VARCHAR2(20) NOT NULL
                CONSTRAINT ck_lh_event CHECK (event IN ('MOVE','TRACK_IN','TRACK_OUT','HOLD','RELEASE','SPC_REVIEW','TRACKIN_FAIL')),
  operation     VARCHAR2(30),
  equipment_id  VARCHAR2(20),
  user_name     VARCHAR2(60) NOT NULL,
  comments      VARCHAR2(500),
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_lh_lot ON lot_history(lot_id, created_at);

CREATE TABLE user_roles (
  user_name   VARCHAR2(60) NOT NULL,
  role        VARCHAR2(20) NOT NULL
              CONSTRAINT ck_ur_role CHECK (role IN ('OPERATOR','TECHNICIAN','ENGINEER','SUPERVISOR')),
  operation   VARCHAR2(30) NOT NULL,
  granted_by  VARCHAR2(60) DEFAULT 'seed' NOT NULL,
  granted_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_user_roles PRIMARY KEY (user_name, role, operation)
);

-- Simulated "long running session" records (stand-in for V$SESSION, for the db-slow-query scenario)
CREATE TABLE db_sessions (
  session_id   NUMBER PRIMARY KEY,
  username     VARCHAR2(30) NOT NULL,
  module       VARCHAR2(60),
  sql_id       VARCHAR2(20),
  sql_text     VARCHAR2(1000),
  elapsed_sec  NUMBER NOT NULL,
  wait_event   VARCHAR2(60),
  status       VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL
               CONSTRAINT ck_dbs_status CHECK (status IN ('ACTIVE','INACTIVE','KILLED')),
  started_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

------------------------------------------------------------------
-- Agent / governance
------------------------------------------------------------------
CREATE TABLE agent_runs (
  run_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id  VARCHAR2(15) NOT NULL REFERENCES incidents(incident_id),
  skill_used   VARCHAR2(60),
  status       VARCHAR2(20) DEFAULT 'Running' NOT NULL
               CONSTRAINT ck_run_status CHECK (status IN ('Running','Completed','Failed','Timeout')),
  llm_mode     VARCHAR2(10) NOT NULL CONSTRAINT ck_run_mode CHECK (llm_mode IN ('llm','mock')),
  tool_calls   NUMBER DEFAULT 0 NOT NULL,
  root_cause   VARCHAR2(2000),
  summary      VARCHAR2(4000),
  started_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  finished_at  TIMESTAMP
);
CREATE INDEX ix_run_incident ON agent_runs(incident_id);

CREATE TABLE agent_steps (
  run_id      NUMBER NOT NULL REFERENCES agent_runs(run_id),
  step_no     NUMBER NOT NULL,
  step_type   VARCHAR2(20) NOT NULL
              CONSTRAINT ck_step_type CHECK (step_type IN ('thought','tool_call','tool_result','skill_loaded','proposal','verify','error','final')),
  content     CLOB,
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_agent_steps PRIMARY KEY (run_id, step_no)
);

CREATE TABLE action_requests (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_id   VARCHAR2(15) NOT NULL REFERENCES incidents(incident_id),
  run_id        NUMBER REFERENCES agent_runs(run_id),
  action_type   VARCHAR2(30) NOT NULL
                CONSTRAINT ck_act_type CHECK (action_type IN ('release_lot_hold','set_equipment_state','reset_interface','grant_user_role','escalate_to_group')),
  params        CLOB CONSTRAINT ck_act_params CHECK (params IS JSON),
  risk          VARCHAR2(10) NOT NULL CONSTRAINT ck_act_risk CHECK (risk IN ('low','medium','high')),
  reason        VARCHAR2(2000) NOT NULL,
  status        VARCHAR2(10) DEFAULT 'Pending' NOT NULL
                CONSTRAINT ck_act_status CHECK (status IN ('Pending','Approved','Rejected','Executed','Failed')),
  requested_by  VARCHAR2(60) DEFAULT 'agent' NOT NULL,
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  decided_by    VARCHAR2(60),
  decided_at    TIMESTAMP,
  executed_at   TIMESTAMP,
  result        VARCHAR2(4000)
);
CREATE INDEX ix_act_incident ON action_requests(incident_id);
CREATE INDEX ix_act_status   ON action_requests(status);

CREATE TABLE audit_log (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  who           VARCHAR2(60)  NOT NULL,
  what          VARCHAR2(60)  NOT NULL,
  target        VARCHAR2(100) NOT NULL,
  before_value  VARCHAR2(4000),
  after_value   VARCHAR2(4000),
  at_time       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_audit_at ON audit_log(at_time);

-- Marker row written at the very end of 05_seed.sql; remedy-api waits for it before reporting healthy.
CREATE TABLE schema_info (
  info_key    VARCHAR2(30) PRIMARY KEY,
  info_value  VARCHAR2(200),
  updated_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);
